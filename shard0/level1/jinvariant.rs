fn j_invariant_godel() -> u128 {
    let mut g: u128 = 1;
    
    for (i, &coeff) in J_COEFFICIENTS.iter().enumerate() {
        if coeff > 0 {
            // Cap exponent to prevent overflow
            let exp = coeff.min(10) as u32;
            g = g.saturating_mul(PRIMES_71[i].pow(exp) as u128);
        }
    }
    
    g
}

